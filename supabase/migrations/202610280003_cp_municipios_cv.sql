/*
  De un código postal a su municipio.

  Un 21 % de los códigos postales españoles los comparten varios municipios,
  y en la cartera eso son 506 clientes. Para esos se usa el municipio escrito
  en la ficha como desempate —ahí sí vale, porque solo hay que elegir entre
  dos o tres candidatos conocidos— y, si tampoco cuadra, el de código más
  bajo, que al menos es siempre el mismo y no baila entre consultas.
*/
create or replace function public.municipio_de_cp(p_postal text, p_texto text default null)
returns char(5)
language sql
stable
set search_path to 'public'
as $$
  with candidatos as (
    select m.ine, m.name
    from public.cp_municipios m
    where m.postal_code = lpad(nullif(regexp_replace(coalesce(p_postal, ''), '\D', '', 'g'), ''), 5, '0')
  )
  select ine from (
    select c.ine,
           case when public.municipio_llano(c.name) = public.municipio_llano(p_texto) then 0 else 1 end as orden
    from candidatos c
  ) ordenados
  order by orden, ine
  limit 1;
$$;

comment on table public.cp_municipios is
  'Código postal a municipio del INE, solo Comunidad Valenciana. Es lo que permite dibujar el mapa municipal sin depender del municipio escrito a mano en Sage.';

