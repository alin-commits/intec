-- El municipio de cada código postal de la Comunidad Valenciana.
--
-- Para qué: el municipio escrito en la ficha de Sage no sirve para dibujar un
-- mapa. Con los datos del 28/10/2026 hay 1.916 grafías distintas, y entre
-- ellas cosas que no son municipios —«TORRELLANO-ELCHE», «MATOLA»,
-- «ARNEVA (ORIHUELA)» son pedanías— y el mismo sitio escrito de varias
-- formas: «ALICANTE» y «Alicante (Alacant)», «SAN VICENTE DEL RASPEIG» y
-- «Sant Vicent del Raspeig». Casar eso contra un mapa falla justo donde
-- interesa.
--
-- El código postal sí es una clave: de los 6.943 clientes, 6.352 (91 %)
-- resuelven a un municipio por su CP. Y el código que sale de aquí es el del
-- INE, que es el mismo que identifica cada contorno del mapa, así que no hay
-- que casar ningún nombre en ningún sitio.
--
-- Solo la Comunidad Valenciana (03, 12, 46), que es donde está el grueso de la
-- cartera y donde está dibujado el mapa municipal. Ampliarlo a otra comunidad
-- es volver a generar estas filas con sus provincias.
--
-- Origen de los datos: ds-codigos-postales-ine-es (datos abiertos). Se puede
-- volver a ejecutar sin romper nada.

create table if not exists public.cp_municipios (
  postal_code char(5) not null,
  ine char(5) not null,
  name text not null,
  primary key (postal_code, ine)
);
create index if not exists cp_municipios_ine on public.cp_municipios (ine);

alter table public.cp_municipios enable row level security;
drop policy if exists cp_municipios_read on public.cp_municipios;
create policy cp_municipios_read on public.cp_municipios for select to authenticated using (true);
revoke insert, update, delete, truncate on public.cp_municipios from anon, authenticated;

